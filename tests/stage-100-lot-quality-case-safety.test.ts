import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
test("Stage 100: safe branch-scoped nonconformance requires an existing active recall escalation",()=>{
 const api=readFileSync("src/app/api/inventory/lot-quality-cases/route.ts","utf8");
 const page=readFileSync("src/app/inventory/lot-impact/[lotId]/page.tsx","utf8");
 const ui=readFileSync("src/components/recall-quality-case-manager.tsx","utf8");
 const schema=readFileSync("prisma/schema.prisma","utf8");
 const sql=readFileSync("prisma/migrations/20261012235000_inventory_recall_quality_case_link/migration.sql","utf8");
 assert.match(api,/quality.nonconformance.manage/);
 assert.match(api,/inventory.view/);
 assert.match(api,/session.activeBranchId/);
 assert.match(api,/tx.userBranchScope.findUnique/);
 assert.match(api,/tx.branch.findFirst/);
 assert.match(api,/organization_id=\$\{organizationId\}/);
 assert.match(api,/FOR UPDATE/);
 assert.match(api,/lot.safetyStatus!=="QUARANTINED"/);
 assert.match(api,/latest.id!==safetyEventId/);
 assert.match(api,/action:"ESCALATED_TO_QUALITY"/);
 assert.match(api,/branchId,safetyEventId,action:/);
 assert.match(api,/tx.nonconformance.create/);
 assert.match(api,/tx.inventoryLotQualityCase.create/);
 assert.match(api,/tx.auditEvent.create/);
 assert.match(api,/INVENTORY_RECALL_QUALITY_CASE_OPENED/);
 assert.match(api,/clinicalExposure:"NOT_DETERMINED"/);
 assert.match(api,/isolationLevel:"Serializable"/);
 assert.match(api,/quality_case_already_linked/);
 assert.doesNotMatch(api,/tx.patient|tx.laboratoryResult|tx.inventoryLot.update|tx.stockMovement.create/);
 assert.match(page,/RecallQualityCaseManager/);
 assert.match(page,/responses.some\(r=>r.action==="ESCALATED_TO_QUALITY"\)/);
 assert.match(page,/branchId:activeBranchId/);
 assert.match(ui,/type="submit"/);
 assert.match(ui,/router.refresh\(\)/);
 assert.match(ui,/This is not evidence of patient exposure/);
 assert.match(schema,/model InventoryLotQualityCase \{/);
 assert.match(sql,/UNIQUE KEY `ilqc_event_branch_unique`/);
 assert.match(sql,/REFERENCES `nonconformances`/);
 assert.match(sql,/REFERENCES `inventory_lot_safety_events`/);
});
