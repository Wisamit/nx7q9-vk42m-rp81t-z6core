-- Phase 4E: immutable client/corporate account statements.

CREATE TABLE `client_account_statements` (
  `id` CHAR(36) NOT NULL,
  `organization_id` CHAR(36) NOT NULL,
  `client_id` CHAR(36) NOT NULL,
  `branch_id` CHAR(36) NULL,
  `statement_number` VARCHAR(50) NOT NULL,
  `status` ENUM('ISSUED','VOIDED') NOT NULL DEFAULT 'ISSUED',
  `currency` CHAR(3) NOT NULL,
  `period_start` DATE NOT NULL,
  `period_end` DATE NOT NULL,
  `timezone_snapshot` VARCHAR(64) NOT NULL,
  `client_code_snapshot` VARCHAR(60) NOT NULL,
  `client_name_en_snapshot` VARCHAR(220) NOT NULL,
  `client_name_ar_snapshot` VARCHAR(220) NULL,
  `payment_terms_days_snapshot` INT NULL,
  `branch_code_snapshot` VARCHAR(50) NULL,
  `branch_name_en_snapshot` VARCHAR(200) NULL,
  `branch_name_ar_snapshot` VARCHAR(200) NULL,
  `opening_balance` DECIMAL(18,4) NOT NULL,
  `invoice_charges` DECIMAL(18,4) NOT NULL,
  `credit_notes` DECIMAL(18,4) NOT NULL,
  `payments` DECIMAL(18,4) NOT NULL,
  `refunds` DECIMAL(18,4) NOT NULL,
  `closing_balance` DECIMAL(18,4) NOT NULL,
  `generated_by_user_id` CHAR(36) NOT NULL,
  `generated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE INDEX `client_statements_org_number_key`(`organization_id`,`statement_number`),
  INDEX `client_statements_client_currency_period_idx`(`client_id`,`currency`,`period_start`,`period_end`),
  INDEX `client_statements_branch_generated_idx`(`branch_id`,`generated_at`),
  INDEX `client_statements_generator_generated_idx`(`generated_by_user_id`,`generated_at`),
  CONSTRAINT `client_statements_org_fkey` FOREIGN KEY (`organization_id`) REFERENCES `organizations`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `client_statements_client_fkey` FOREIGN KEY (`client_id`) REFERENCES `clients`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `client_statements_branch_fkey` FOREIGN KEY (`branch_id`) REFERENCES `branches`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `client_statements_generator_fkey` FOREIGN KEY (`generated_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `client_account_statement_lines` (
  `id` CHAR(36) NOT NULL,
  `statement_id` CHAR(36) NOT NULL,
  `line_type` ENUM('INVOICE','CREDIT_NOTE','PAYMENT','REFUND') NOT NULL,
  `source_id` CHAR(36) NOT NULL,
  `source_number` VARCHAR(80) NOT NULL,
  `branch_id_snapshot` CHAR(36) NOT NULL,
  `branch_code_snapshot` VARCHAR(50) NOT NULL,
  `occurred_at` DATETIME(3) NOT NULL,
  `description` VARCHAR(500) NOT NULL,
  `debit_amount` DECIMAL(18,4) NOT NULL DEFAULT 0,
  `credit_amount` DECIMAL(18,4) NOT NULL DEFAULT 0,
  `running_balance` DECIMAL(18,4) NOT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  INDEX `client_statement_lines_statement_occurred_idx`(`statement_id`,`occurred_at`),
  INDEX `client_statement_lines_source_type_idx`(`source_id`,`line_type`),
  CONSTRAINT `client_statement_lines_statement_fkey` FOREIGN KEY (`statement_id`) REFERENCES `client_account_statements`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
