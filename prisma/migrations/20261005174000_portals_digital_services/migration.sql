CREATE TABLE `portal_accounts` (
  `id` CHAR(36) NOT NULL,
  `organization_id` CHAR(36) NOT NULL,
  `type` ENUM('PATIENT','DOCTOR','CORPORATE') NOT NULL,
  `patient_id` CHAR(36) NULL,
  `referrer_id` CHAR(36) NULL,
  `client_id` CHAR(36) NULL,
  `email` VARCHAR(191) NULL,
  `normalized_email` VARCHAR(191) NULL,
  `phone` VARCHAR(50) NULL,
  `normalized_phone` VARCHAR(50) NULL,
  `password_hash` VARCHAR(255) NULL,
  `preferred_locale` VARCHAR(10) NOT NULL DEFAULT 'en',
  `status` ENUM('INVITED','ACTIVE','LOCKED','DISABLED') NOT NULL DEFAULT 'INVITED',
  `contact_verified_at` DATETIME(3) NULL,
  `last_login_at` DATETIME(3) NULL,
  `failed_login_attempts` INT NOT NULL DEFAULT 0,
  `locked_until` DATETIME(3) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  `deactivated_at` DATETIME(3) NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `portal_accounts_patient_id_key`(`patient_id`),
  UNIQUE INDEX `portal_accounts_referrer_id_key`(`referrer_id`),
  UNIQUE INDEX `portal_accounts_client_id_key`(`client_id`),
  INDEX `portal_accounts_org_type_status_idx`(`organization_id`,`type`,`status`),
  INDEX `portal_accounts_org_email_idx`(`organization_id`,`normalized_email`),
  INDEX `portal_accounts_org_phone_idx`(`organization_id`,`normalized_phone`),
  CONSTRAINT `portal_accounts_org_fkey` FOREIGN KEY (`organization_id`) REFERENCES `organizations`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `portal_accounts_patient_fkey` FOREIGN KEY (`patient_id`) REFERENCES `patients`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `portal_accounts_referrer_fkey` FOREIGN KEY (`referrer_id`) REFERENCES `referrers`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `portal_accounts_client_fkey` FOREIGN KEY (`client_id`) REFERENCES `clients`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

