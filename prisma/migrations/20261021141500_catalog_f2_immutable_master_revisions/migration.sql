-- F2: new effective-dated overlays for masters that lack native version tables.
-- Never rewrite old released clinical, billing or catalog master references.
CREATE TABLE `catalog_config_revisions` (
  `id` CHAR(36) NOT NULL,
  `organization_id` CHAR(36) NOT NULL,
  `branch_id` CHAR(36) NOT NULL,
  `source_batch_id` CHAR(36) NOT NULL,
  `source_row_number` INTEGER NOT NULL,
  `entity_type` VARCHAR(40) NOT NULL,
  `entity_id` CHAR(36) NOT NULL,
  `revision` INTEGER NOT NULL,
  `effective_from` DATETIME(3) NOT NULL,
  `effective_to` DATETIME(3) NULL,
  `state` ENUM('RECORDED','CANCELLED') NOT NULL DEFAULT 'RECORDED',
  `before_snapshot` JSON NOT NULL,
  `after_snapshot` JSON NOT NULL,
  `original_digest` CHAR(64) NOT NULL,
  `desired_digest` CHAR(64) NOT NULL,
  `plan_digest` CHAR(64) NOT NULL,
  `created_by_user_id` CHAR(36) NOT NULL,
  `clinical_signer_user_id` CHAR(36) NOT NULL,
  `financial_signer_user_id` CHAR(36) NOT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `cancelled_at` DATETIME(3) NULL,
  `cancelled_by_user_id` CHAR(36) NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `f2_config_batch_row_uq` (`source_batch_id`,`source_row_number`),
  UNIQUE KEY `f2_config_master_revision_uq` (`organization_id`,`entity_type`,`entity_id`,`revision`),
  KEY `f2_config_effective_lookup_idx` (`organization_id`,`entity_type`,`entity_id`,`state`,`effective_from`),
  KEY `f2_config_branch_effective_idx` (`organization_id`,`branch_id`,`effective_from`),
  KEY `f2_config_branch_fk_idx` (`branch_id`),
  KEY `f2_config_created_by_fk_idx` (`created_by_user_id`),
  KEY `f2_config_clinical_fk_idx` (`clinical_signer_user_id`),
  KEY `f2_config_financial_fk_idx` (`financial_signer_user_id`),
  KEY `f2_config_cancelled_by_fk_idx` (`cancelled_by_user_id`),
  CONSTRAINT `f2_config_org_fk` FOREIGN KEY (`organization_id`) REFERENCES `organizations`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `f2_config_branch_fk` FOREIGN KEY (`branch_id`) REFERENCES `branches`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `f2_config_batch_fk` FOREIGN KEY (`source_batch_id`) REFERENCES `catalog_import_batches`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `f2_config_created_by_fk` FOREIGN KEY (`created_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `f2_config_clinical_fk` FOREIGN KEY (`clinical_signer_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `f2_config_financial_fk` FOREIGN KEY (`financial_signer_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `f2_config_cancelled_by_fk` FOREIGN KEY (`cancelled_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
