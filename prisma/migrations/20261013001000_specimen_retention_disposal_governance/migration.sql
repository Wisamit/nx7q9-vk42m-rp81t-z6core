-- Stage 101: forward-only, policy-driven retained-specimen disposal.
-- No default clinical retention duration is installed; policies require independent approval.
CREATE TABLE `specimen_retention_policies` (
  `id` CHAR(36) NOT NULL,
  `organization_id` CHAR(36) NOT NULL,
  `branch_id` CHAR(36) NOT NULL,
  `specimen_type_id` CHAR(36) NOT NULL,
  `minimum_days` INTEGER NOT NULL,
  `rationale` VARCHAR(1000) NOT NULL,
  `status` VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
  `created_by_user_id` CHAR(36) NOT NULL,
  `approved_by_user_id` CHAR(36) NULL,
  `approved_at` DATETIME(3) NULL,
  `retired_by_user_id` CHAR(36) NULL,
  `retired_at` DATETIME(3) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX `srp_scope_status_idx` (`organization_id`,`branch_id`,`specimen_type_id`,`status`,`approved_at`),
  CONSTRAINT `srp_minimum_days_chk` CHECK (`minimum_days` BETWEEN 1 AND 73000),
  CONSTRAINT `srp_status_chk` CHECK (`status` IN ('DRAFT','APPROVED','RETIRED')),
  CONSTRAINT `srp_independent_review_chk` CHECK (`approved_by_user_id` IS NULL OR `approved_by_user_id` <> `created_by_user_id`),
  CONSTRAINT `srp_approved_provenance_chk` CHECK (`status` <> 'APPROVED' OR (`approved_by_user_id` IS NOT NULL AND `approved_at` IS NOT NULL)),
  PRIMARY KEY (`id`),
  CONSTRAINT `srp_org_fk` FOREIGN KEY (`organization_id`) REFERENCES `organizations`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `srp_branch_fk` FOREIGN KEY (`branch_id`) REFERENCES `branches`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `srp_type_fk` FOREIGN KEY (`specimen_type_id`) REFERENCES `specimen_types`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `srp_creator_fk` FOREIGN KEY (`created_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `srp_approver_fk` FOREIGN KEY (`approved_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `srp_retirer_fk` FOREIGN KEY (`retired_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `specimen_disposal_cases` (
  `id` CHAR(36) NOT NULL,
  `organization_id` CHAR(36) NOT NULL,
  `branch_id` CHAR(36) NOT NULL,
  `specimen_id` CHAR(36) NOT NULL,
  `policy_id` CHAR(36) NOT NULL,
  `status` VARCHAR(16) NOT NULL DEFAULT 'REQUESTED',
  `reason` VARCHAR(1000) NOT NULL,
  `specimen_version` INTEGER NOT NULL,
  `retention_due_at` DATETIME(3) NOT NULL,
  `requested_by_user_id` CHAR(36) NOT NULL,
  `authorized_by_user_id` CHAR(36) NULL,
  `authorized_at` DATETIME(3) NULL,
  `executed_by_user_id` CHAR(36) NULL,
  `executed_at` DATETIME(3) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX `sdc_branch_queue_idx` (`organization_id`,`branch_id`,`status`,`created_at`),
  INDEX `sdc_specimen_status_idx` (`specimen_id`,`status`),
  CONSTRAINT `sdc_status_chk` CHECK (`status` IN ('REQUESTED','AUTHORIZED','EXECUTED','CANCELLED')),
  CONSTRAINT `sdc_independent_review_chk` CHECK (`authorized_by_user_id` IS NULL OR `authorized_by_user_id` <> `requested_by_user_id`),
  CONSTRAINT `sdc_independent_execution_chk` CHECK (`executed_by_user_id` IS NULL OR `authorized_by_user_id` IS NULL OR `executed_by_user_id` <> `authorized_by_user_id`),
  CONSTRAINT `sdc_execution_provenance_chk` CHECK (`status` <> 'EXECUTED' OR (`authorized_by_user_id` IS NOT NULL AND `authorized_at` IS NOT NULL AND `executed_by_user_id` IS NOT NULL AND `executed_at` IS NOT NULL)),
  PRIMARY KEY (`id`),
  CONSTRAINT `sdc_org_fk` FOREIGN KEY (`organization_id`) REFERENCES `organizations`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `sdc_branch_fk` FOREIGN KEY (`branch_id`) REFERENCES `branches`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `sdc_specimen_fk` FOREIGN KEY (`specimen_id`) REFERENCES `specimens`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `sdc_policy_fk` FOREIGN KEY (`policy_id`) REFERENCES `specimen_retention_policies`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `sdc_requester_fk` FOREIGN KEY (`requested_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `sdc_authorizer_fk` FOREIGN KEY (`authorized_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `sdc_executor_fk` FOREIGN KEY (`executed_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
