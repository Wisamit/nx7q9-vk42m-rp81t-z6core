-- Stage 94: staff-only clinical handover; no changes to released reports, billing or original order notes.
CREATE TABLE `order_clinical_notes` (
 `id` CHAR(36) NOT NULL,
 `organization_id` CHAR(36) NOT NULL,
 `branch_id` CHAR(36) NOT NULL,
 `order_id` CHAR(36) NOT NULL,
 `thread_id` CHAR(36) NOT NULL,
 `revision_number` INT NOT NULL,
 `client_request_id` CHAR(36) NOT NULL,
 `request_fingerprint` CHAR(64) NOT NULL,
 `category` ENUM('CLINICAL_CONTEXT','COLLECTION_INSTRUCTION','LAB_HANDOVER','QUALITY_CAUTION') NOT NULL,
 `language` VARCHAR(2) NOT NULL,
 `body` TEXT NOT NULL,
 `status` ENUM('ACTIVE','SUPERSEDED','RETRACTED') NOT NULL DEFAULT 'ACTIVE',
 `requires_acknowledgement` BOOLEAN NOT NULL DEFAULT FALSE,
 `replaces_note_id` CHAR(36) NULL,
 `correction_reason` VARCHAR(1000) NULL,
 `created_by_user_id` CHAR(36) NOT NULL,
 `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 `retired_by_user_id` CHAR(36) NULL,
 `retired_at` DATETIME(3) NULL,
 `retirement_reason` VARCHAR(1000) NULL,
 PRIMARY KEY (`id`),
 UNIQUE INDEX `ocn_order_thread_revision_uq` (`order_id`, `thread_id`, `revision_number`),
 UNIQUE INDEX `ocn_idempotent_request_uq` (`organization_id`, `created_by_user_id`, `client_request_id`),
 UNIQUE INDEX `order_clinical_notes_replaces_note_id_key` (`replaces_note_id`),
 INDEX `ocn_order_status_idx` (`organization_id`,`branch_id`,`order_id`,`status`),
 INDEX `ocn_order_timeline_idx` (`order_id`,`created_at`,`id`),
 INDEX `ocn_branch_fk_idx` (`branch_id`),
 INDEX `ocn_author_fk_idx` (`created_by_user_id`),
 INDEX `ocn_retirer_fk_idx` (`retired_by_user_id`),
 CONSTRAINT `ocn_org_fk` FOREIGN KEY (`organization_id`) REFERENCES `organizations`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT `ocn_branch_fk` FOREIGN KEY (`branch_id`) REFERENCES `branches`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT `ocn_order_fk` FOREIGN KEY (`order_id`) REFERENCES `orders`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT `ocn_author_fk` FOREIGN KEY (`created_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT `ocn_retirer_fk` FOREIGN KEY (`retired_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT `ocn_replaced_fk` FOREIGN KEY (`replaces_note_id`) REFERENCES `order_clinical_notes`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `order_clinical_note_acknowledgements` (
 `id` CHAR(36) NOT NULL,
 `note_id` CHAR(36) NOT NULL,
 `acknowledged_by_user_id` CHAR(36) NOT NULL,
 `acknowledged_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY (`id`),
 UNIQUE INDEX `ocna_note_user_uq` (`note_id`,`acknowledged_by_user_id`),
 INDEX `ocna_user_at_idx` (`acknowledged_by_user_id`,`acknowledged_at`),
 CONSTRAINT `ocna_note_fk` FOREIGN KEY (`note_id`) REFERENCES `order_clinical_notes`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT `ocna_user_fk` FOREIGN KEY (`acknowledged_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
