CREATE TABLE `order_questions` (
  `id` CHAR(36) NOT NULL,
  `organization_id` CHAR(36) NOT NULL,
  `test_id` CHAR(36) NOT NULL,
  `code` VARCHAR(100) NOT NULL,
  `question_en` VARCHAR(500) NOT NULL,
  `question_ar` VARCHAR(500) NULL,
  `response_type` ENUM('TEXT','NUMERIC','BOOLEAN','DATE','SINGLE_CHOICE') NOT NULL,
  `required` BOOLEAN NOT NULL DEFAULT false,
  `options` JSON NULL,
  `display_order` INTEGER NOT NULL DEFAULT 0,
  `status` ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  `deactivated_at` DATETIME(3) NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `order_questions_test_code_key`(`test_id`,`code`),
  INDEX `order_questions_org_status_idx`(`organization_id`,`status`),
  INDEX `order_questions_test_status_order_idx`(`test_id`,`status`,`display_order`),
  CONSTRAINT `order_questions_org_fkey` FOREIGN KEY (`organization_id`) REFERENCES `organizations`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `order_questions_test_fkey` FOREIGN KEY (`test_id`) REFERENCES `lab_tests`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `order_answers` (
  `id` CHAR(36) NOT NULL,
  `organization_id` CHAR(36) NOT NULL,
  `order_id` CHAR(36) NOT NULL,
  `order_item_id` CHAR(36) NOT NULL,
  `question_id` CHAR(36) NOT NULL,
  `question_code_snapshot` VARCHAR(100) NOT NULL,
  `question_text_en_snapshot` VARCHAR(500) NOT NULL,
  `question_text_ar_snapshot` VARCHAR(500) NULL,
  `response_type_snapshot` ENUM('TEXT','NUMERIC','BOOLEAN','DATE','SINGLE_CHOICE') NOT NULL,
  `answer_text` TEXT NULL,
  `answer_numeric` DECIMAL(18,6) NULL,
  `answer_boolean` BOOLEAN NULL,
  `answer_date` DATE NULL,
  `selected_option_snapshot` VARCHAR(500) NULL,
  `recorded_by_user_id` CHAR(36) NOT NULL,
  `recorded_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE INDEX `order_answers_item_question_key`(`order_item_id`,`question_id`),
  INDEX `order_answers_org_order_idx`(`organization_id`,`order_id`),
  INDEX `order_answers_question_recorded_idx`(`question_id`,`recorded_at`),
  CONSTRAINT `order_answers_org_fkey` FOREIGN KEY (`organization_id`) REFERENCES `organizations`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `order_answers_order_fkey` FOREIGN KEY (`order_id`) REFERENCES `orders`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `order_answers_item_fkey` FOREIGN KEY (`order_item_id`) REFERENCES `order_items`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `order_answers_question_fkey` FOREIGN KEY (`question_id`) REFERENCES `order_questions`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `order_answers_recorder_fkey` FOREIGN KEY (`recorded_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
