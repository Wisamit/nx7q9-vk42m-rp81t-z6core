-- Stage 90: EQA / proficiency testing evidence is branch-bound and append-only
-- after submission/review. Never alter patient clinical results or QC disposition.
CREATE TABLE `eqa_programs` (
  `id` CHAR(36) NOT NULL,
  `organization_id` CHAR(36) NOT NULL,
  `branch_id` CHAR(36) NOT NULL,
  `code` VARCHAR(80) NOT NULL,
  `provider_name` VARCHAR(220) NOT NULL,
  `name_en` VARCHAR(220) NOT NULL,
  `name_ar` VARCHAR(220) NULL,
  `status` ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  `created_by_user_id` CHAR(36) NOT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `eqa_programs_branch_id_code_key` (`branch_id`,`code`),
  INDEX `eqa_programs_organization_id_status_idx` (`organization_id`,`status`),
  CONSTRAINT `eqa_programs_organization_id_fkey` FOREIGN KEY (`organization_id`) REFERENCES `organizations`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `eqa_programs_branch_id_fkey` FOREIGN KEY (`branch_id`) REFERENCES `branches`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `eqa_programs_created_by_user_id_fkey` FOREIGN KEY (`created_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `eqa_rounds` (
  `id` CHAR(36) NOT NULL,
  `program_id` CHAR(36) NOT NULL,
  `round_code` VARCHAR(80) NOT NULL,
  `sample_code` VARCHAR(120) NOT NULL,
  `due_at` DATETIME(3) NULL,
  `status` ENUM('OPEN','SUBMITTED','ASSESSED','CLOSED') NOT NULL DEFAULT 'OPEN',
  `created_by_user_id` CHAR(36) NOT NULL,
  `submitted_by_user_id` CHAR(36) NULL,
  `submitted_at` DATETIME(3) NULL,
  `reviewed_by_user_id` CHAR(36) NULL,
  `reviewed_at` DATETIME(3) NULL,
  `review_reason` VARCHAR(1000) NULL,
  `closed_by_user_id` CHAR(36) NULL,
  `closed_at` DATETIME(3) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `eqa_rounds_program_id_round_code_key` (`program_id`,`round_code`),
  INDEX `eqa_rounds_status_due_at_idx` (`status`,`due_at`),
  CONSTRAINT `eqa_rounds_program_id_fkey` FOREIGN KEY (`program_id`) REFERENCES `eqa_programs`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `eqa_rounds_created_by_user_id_fkey` FOREIGN KEY (`created_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `eqa_rounds_submitted_by_user_id_fkey` FOREIGN KEY (`submitted_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `eqa_rounds_reviewed_by_user_id_fkey` FOREIGN KEY (`reviewed_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `eqa_rounds_closed_by_user_id_fkey` FOREIGN KEY (`closed_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `eqa_observations` (
  `id` CHAR(36) NOT NULL,
  `round_id` CHAR(36) NOT NULL,
  `entry_code` VARCHAR(80) NOT NULL,
  `component_id` CHAR(36) NOT NULL,
  `analyzer_id` CHAR(36) NULL,
  `component_code_snapshot` VARCHAR(80) NOT NULL,
  `component_name_en_snapshot` VARCHAR(200) NOT NULL,
  `component_name_ar_snapshot` VARCHAR(200) NULL,
  `unit_snapshot` VARCHAR(80) NULL,
  `analyzer_code_snapshot` VARCHAR(80) NULL,
  `observed_value` VARCHAR(300) NOT NULL,
  `method_snapshot` VARCHAR(220) NULL,
  `note` VARCHAR(1000) NULL,
  `provider_expected_value` VARCHAR(300) NULL,
  `provider_feedback` VARCHAR(1000) NULL,
  `assessment` ENUM('SATISFACTORY','UNSATISFACTORY','NOT_EVALUATED') NULL,
  `assessed_by_user_id` CHAR(36) NULL,
  `assessed_at` DATETIME(3) NULL,
  `created_by_user_id` CHAR(36) NOT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE INDEX `eqa_observations_round_id_entry_code_key` (`round_id`,`entry_code`),
  INDEX `eqa_observations_component_id_created_at_idx` (`component_id`,`created_at`),
  CONSTRAINT `eqa_observations_round_id_fkey` FOREIGN KEY (`round_id`) REFERENCES `eqa_rounds`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `eqa_observations_component_id_fkey` FOREIGN KEY (`component_id`) REFERENCES `test_components`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `eqa_observations_analyzer_id_fkey` FOREIGN KEY (`analyzer_id`) REFERENCES `analyzers`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `eqa_observations_created_by_user_id_fkey` FOREIGN KEY (`created_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `eqa_observations_assessed_by_user_id_fkey` FOREIGN KEY (`assessed_by_user_id`) REFERENCES `users`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
